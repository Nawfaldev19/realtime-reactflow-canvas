export type Mutation = {
  __typename?: 'Mutation';
  /**
   * Owners and editors. Makes a new diagram in the same workspace from a version. Every step and connector
   * gets a new id and every reference (group parents, connector ends, the saved manual arrangement) is
   * rewritten to the new ids; stable identity keys stay the same. `copyLog` lists references that could
   * not be carried over.
   */
  copyVersion: CopyVersionPayload;
  /** Owners and editors. The new diagram starts with a three-node starter plan. */
  createDiagram: CreateDiagramPayload;
  /** Owners and editors. Deletes the diagram and its versions. */
  deleteDiagram: DeleteDiagramPayload;
  /** Owners and editors. Renaming does not change the document revision. */
  renameDiagram: RenameDiagramPayload;
  /**
   * Owners and editors. Starts restoring a version: the diagram as stored now is kept as a "Before
   * restoring vN" version (unless nothing changed since the latest version), and the version to restore
   * is returned. The editor then applies the restore as one operation, which the collaboration channel
   * (or, with collaboration off, saveDiagram) stores and every open editor receives, and which the
   * person can undo in one step.
   */
  restoreVersion: RestoreVersionPayload;
  /**
   * Owners and editors. Replaces the document (and optionally the view settings) when `baseRevision`
   * equals the stored revision. A stale save returns a REVISION_CONFLICT error and the stored diagram.
   */
  saveDiagram: SaveDiagramPayload;
  /**
   * Owners and editors. Takes a version of the diagram as stored now. A manual version (the default) is
   * always made. An automatic one (the editor's periodic version) is skipped when nothing changed since
   * the latest version or when a version is less than five minutes old; `created` is then false and
   * `version` is the latest one.
   */
  saveVersion: SaveVersionPayload;
  /**
   * Owners. Turns live collaboration on or off for a diagram. Every open editor is told at once through
   * the diagram's channel: with it on, edits are operations the server orders and stores; with it off,
   * each editor autosaves whole documents with a revision check.
   */
  setCollaboration: SetCollaborationPayload;
  /** Sets the signed-in member's own navigation mode; null goes back to each workspace's default. */
  setNavigationMode: SetNavigationModePayload;
  /** Owners only. Sets the navigation mode for members of the workspace who have not chosen their own. */
  setWorkspaceNavigationMode: SetWorkspaceNavigationModePayload;
  /** Demo sign-in: pick a person and receive a signed, expiring bearer token */
  signInAsDemo: SignInAsDemoPayload;
  /**
   * Owners and editors. Replaces the view settings (opening view, background, animation, snapping).
   * The document revision does not change, so this never conflicts with an edit to the nodes.
   */
  updateViewSettings: UpdateViewSettingsPayload;
};


