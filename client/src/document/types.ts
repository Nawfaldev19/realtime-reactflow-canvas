// The persisted diagram document, version 1. The server validates the same
// shape (server/app/services/diagram_document.rb); docs/ARCHITECTURE.md
// summarises the fields.

export const SCHEMA_VERSION = 1;

export const NODE_KINDS = [
  "step",
  "decision",
  "start-end",
  "note",
  "label",
  "shape",
  "line",
  "sketch",
  "group",
] as const;
export type NodeKind = (typeof NODE_KINDS)[number];

export const EDGE_KINDS = ["connector", "floating"] as const;
export type EdgeKind = (typeof EDGE_KINDS)[number];

export const ROUTE_STYLES = ["polyline", "spline", "bezier", "step"] as const;
export type RouteStyle = (typeof ROUTE_STYLES)[number];

export const SIDES = ["top", "right", "bottom", "left"] as const;
export type Side = (typeof SIDES)[number];

export interface Point {
  readonly x: number;
  readonly y: number;
}

export interface Size {
  readonly width: number;
  readonly height: number;
}

/** Visual style. Replaced as a whole on update (one last-writer-wins field). */
export type Style = Readonly<Record<string, string | number | boolean>>;

/**
 * Kind-specific content (text, shape name, line rotation, sketch points…).
 * Updates merge per top-level key, so two people changing different keys
 * never overwrite each other.
 */
export type NodeData = Readonly<Record<string, unknown>>;

export interface DiagramNode {
  /** Client-generated UUID, never reassigned. */
  readonly id: string;
  /** Stable identity key: survives version copies, where ids are remapped. */
  readonly key: string;
  readonly kind: NodeKind;
  /** Short human-readable number ("Step 12"), allocated from the document counter. */
  readonly number: number;
  /** Relative to the parent group when parentId is set, otherwise absolute. */
  readonly position: Point;
  readonly size: Size;
  readonly parentId: string | null;
  /** Stacking order; larger is in front. */
  readonly z: number;
  readonly style: Style;
  readonly data: NodeData;
}

export interface RoutePoint extends Point {
  readonly id: string;
  /** Placed by the user rather than generated by the router. */
  readonly userCreated?: boolean;
  /** Orthogonal routes: the axis this point's segment may move along. */
  readonly axis?: "x" | "y";
}

export interface Route {
  readonly style: RouteStyle;
  readonly points: readonly RoutePoint[];
}

export const TEXT_ALIGNMENTS = ["left", "center", "right"] as const;
export type TextAlignment = (typeof TEXT_ALIGNMENTS)[number];

export interface EdgeLabel {
  readonly text: string;
  /** Position along the path, 0 at the source and 1 at the target. Absent: placed automatically. */
  readonly t?: number;
  readonly fontSize?: number;
  readonly bold?: boolean;
  readonly italic?: boolean;
  readonly underline?: boolean;
  readonly align?: TextAlignment;
  readonly color?: string;
  readonly background?: string;
  readonly maxWidth?: number;
  readonly padding?: number;
  /** A border turns the label into a pill. */
  readonly border?: boolean;
  readonly borderWidth?: number;
  readonly borderColor?: string;
}

export interface DiagramEdge {
  readonly id: string;
  readonly key: string;
  readonly kind: EdgeKind;
  readonly source: string;
  readonly target: string;
  /** null means "choose the side automatically". */
  readonly sourceSide: Side | null;
  readonly targetSide: Side | null;
  readonly route: Route;
  readonly label: EdgeLabel | null;
  readonly style: Style;
}

export const LAYOUT_ENGINES = ["dagre", "layered"] as const;
export type LayoutEngineName = (typeof LAYOUT_ENGINES)[number];

/** TB: ranks run top to bottom; LR: left to right. */
export const LAYOUT_DIRECTIONS = ["TB", "LR"] as const;
export type LayoutDirection = (typeof LAYOUT_DIRECTIONS)[number];

/** Where a node was before the first automatic layout (its own coordinates, relative to its parent). */
export interface NodePlacement {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}

/** A connector's hand-made routing before the first automatic layout. */
export interface EdgePlacement {
  readonly sourceSide: Side | null;
  readonly targetSide: Side | null;
  readonly points: readonly RoutePoint[];
}

/** The author's own arrangement, kept while an automatic layout is shown. */
export interface HandPlacedLayout {
  readonly nodes: Readonly<Record<string, NodePlacement>>;
  readonly edges: Readonly<Record<string, EdgePlacement>>;
}

/** An automatic layout is active. Absent (or null): manual, free positioning. */
export interface DiagramLayout {
  readonly engine: LayoutEngineName;
  readonly direction: LayoutDirection;
  readonly manual: HandPlacedLayout;
}

/** The wire and storage format: ordered lists, parents before children. */
export interface DiagramDocument {
  readonly schemaVersion: typeof SCHEMA_VERSION;
  readonly nodes: readonly DiagramNode[];
  readonly edges: readonly DiagramEdge[];
  /** Next node number to allocate. */
  readonly nextNumber: number;
  /** Present only while an automatic layout is active. */
  readonly layout?: DiagramLayout;
}

/** The in-memory form: keyed collections, so every lookup and update is O(1) by id. */
export interface DocumentState {
  readonly nodes: Readonly<Record<string, DiagramNode>>;
  readonly edges: Readonly<Record<string, DiagramEdge>>;
  readonly nextNumber: number;
  /** The active automatic layout and the manual arrangement it replaced; absent or null in manual mode. */
  readonly layout?: DiagramLayout | null;
}

export const EMPTY_STATE: DocumentState = { nodes: {}, edges: {}, nextNumber: 1 };
